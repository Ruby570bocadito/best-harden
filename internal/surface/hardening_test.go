// Las reglas anti escaneo (flags TCP) solo afectan a paquetes anómalos: no
// pueden convertir un bloqueo en un cierre total del puerto.
func TestTCPFlagsAreNotATotalBlock(t *testing.T) {
	ssh := Port{Proto: "tcp", Port: 22, Addresses: []string{"0.0.0.0"}}
	web := Port{Proto: "tcp", Port: 8080, Addresses: []string{"0.0.0.0"}}

	save := `# Generated by iptables-save v1.8.7 on x
*filter
:INPUT DROP [0:0]
:LOGDROP - [0:0]
-A INPUT -p tcp -m tcp --tcp-flags FIN,SYN,RST,ACK NONE -j DROP
-A INPUT -p tcp -m tcp --tcp-flags ALL ALL -j LOGDROP
-A INPUT -p tcp -m tcp ! --tcp-flags FIN,SYN,RST,ACK SYN -m state --state NEW -j DROP
-A INPUT -p tcp -m tcp ! --syn -m conntrack --ctstate NEW -j DROP
-A INPUT -p tcp -m tcp --dport 22 -j ACCEPT
-A LOGDROP -j LOG
-A LOGDROP -j DROP
COMMIT
`
	fw, err := newLinuxFirewall(nil, save, "")
	if err != nil {
		t.Fatal(err)
	}
	checkCases(t, fw, []fwCase{
		{"iptables: ssh permitido", ssh, FirewallOpen, "", "«INPUT #5»"},
		{"iptables: resto por política", web, FirewallFiltered, "", "descarta por defecto"},
	})
	if r := iptRule(strings.Fields("-p tcp --syn -j ACCEPT"), "ip"); !r.flags || r.unknown || r.verdict != "accept" {
		t.Errorf("--syn: %+v", r)
	}

	nft := `{"nftables":[{"table":{"family":"inet","name":"f"}},
{"chain":{"family":"inet","table":"f","name":"input","type":"filter","hook":"input","prio":0,"policy":"accept"}},
{"rule":{"family":"inet","table":"f","chain":"input","handle":1,"expr":[
 {"match":{"op":"!=","left":{"&":[{"payload":{"protocol":"tcp","field":"flags"}},["fin","syn","rst","ack"]]},"right":"syn"}},
 {"match":{"op":"in","left":{"ct":{"key":"state"}},"right":"new"}},{"drop":null}]}},
{"rule":{"family":"inet","table":"f","chain":"input","handle":2,"expr":[
 {"match":{"op":"==","left":{"payload":{"protocol":"tcp","field":"dport"}},"right":8080}},{"drop":null}]}}]}`
	fw2, err := newLinuxFirewall([]byte(nft), "", "")
	if err != nil {
		t.Fatal(err)
	}
	checkCases(t, fw2, []fwCase{
		{"nft: flags no bloquean", ssh, FirewallOpen, "", "acepta por defecto"},
		{"nft: bloqueo real", web, FirewallFiltered, "", "«input #2»"},
	})
}

func TestFlattenPrefixWithoutAddr(t *testing.T) {
	var v any
	_ = json.Unmarshal([]byte(`{"prefix":{"len":8}}`), &v)
	if got := flatten(v); got != nil {
		t.Errorf("prefijo incompleto: %v", got)
	}
	_ = json.Unmarshal([]byte(`{"prefix":{"addr":"10.0.0.0","len":8}}`), &v)
	if got := flatten(v); len(got) != 1 || got[0] != "10.0.0.0/8" {
		t.Errorf("prefijo: %v", got)
	}
}

// Las referencias «cadena #n» se cuentan por familia y tabla, y se avisa de
// las cadenas de prerouting/ingress que descartan tráfico.
func TestNftCountsAndUncoveredHooks(t *testing.T) {
	nft := `{"nftables":[
{"chain":{"family":"ip","table":"a","name":"input","type":"filter","hook":"input","policy":"accept"}},
{"chain":{"family":"ip6","table":"b","name":"input","type":"filter","hook":"input","policy":"accept"}},
{"chain":{"family":"inet","table":"raw","name":"pre","type":"filter","hook":"prerouting","policy":"accept"}},
{"chain":{"family":"netdev","table":"edge","name":"in","type":"filter","hook":"ingress","policy":"accept"}},
{"rule":{"family":"ip","table":"a","chain":"input","expr":[{"counter":null}]}},
{"rule":{"family":"ip6","table":"b","chain":"input","expr":[{"match":{"op":"==","left":{"payload":{"protocol":"tcp","field":"dport"}},"right":22}},{"drop":null}]}},
{"rule":{"family":"inet","table":"raw","chain":"pre","expr":[{"match":{"op":"==","left":{"fib":{"result":"oif","flags":["saddr","iif"]}},"right":false}},{"drop":null}]}},
{"rule":{"family":"netdev","table":"edge","chain":"in","expr":[{"match":{"op":"==","left":{"payload":{"protocol":"ip","field":"saddr"}},"right":"203.0.113.0/24"}},{"drop":null}]}}]}`
	fw, err := newLinuxFirewall([]byte(nft), "", "")
	if err != nil {
		t.Fatal(err)
	}
	a := fw.Evaluate(Port{Proto: "tcp", Port: 22, Addresses: []string{"::1", "2001:db8::1"}})
	if a.State != FirewallFiltered || !strings.Contains(a.Why, "«input #1»") {
		t.Errorf("la regla de ip6/b es la #1 de su cadena: %+v", a)
	}
	if u := fw.Uncovered(); len(u) != 1 || u[0] != "nft netdev/edge/in" {
		t.Errorf("cadenas sin evaluar (el fib antisuplantación no cuenta): %v", u)
	}
	save := "*raw\n:PREROUTING ACCEPT [0:0]\n-A PREROUTING -s 198.51.100.0/24 -j DROP\nCOMMIT\n*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n"
	fw2, _ := newLinuxFirewall(nil, save, "")
	if u := fw2.Uncovered(); len(u) != 1 || u[0] != "iptables raw PREROUTING" {
		t.Errorf("iptables raw: %v", u)
	}
	if (&Firewall{}).Uncovered() != nil {
		t.Error("Windows no tiene cadenas sin evaluar")
	}
}

// Un bloqueo del Firewall de Windows solo cuenta si es seguro que se aplica
// al programa: por la ruta completa, no por el nombre del fichero.
func TestWindowsBlockNeedsFullPath(t *testing.T) {
	t.Setenv("SystemRoot", `C:\Windows`)
	t.Setenv("ProgramFiles", `C:\Program Files`)
	prof := []FirewallProfile{{Name: "Privado", Bit: 2, Enabled: true, BlockInbound: true, Active: true}}
	allow := FirewallRule{Name: "node", Allow: true, Protocol: 256, App: `%ProgramFiles%\nodejs\node.exe`, Profiles: 7}
	fw := &Firewall{Profiles: prof, Rules: []FirewallRule{
		{Name: "bloquea el de Descargas", Protocol: 256, App: `C:\Users\x\Downloads\node.exe`, Profiles: 7},
		allow,
	}}
	node := Port{Proto: "tcp", Port: 3000, Addresses: []string{"0.0.0.0"}, Process: "node.exe", Path: `C:\Program Files\nodejs\node.exe`}
	if a := fw.Evaluate(node); a.State != FirewallOpen {
		t.Errorf("otro node.exe no lo bloquea: %+v", a)
	}
	// Mismo programa, con variables y otras mayúsculas: sí lo bloquea.
	fw.Rules[0].App = `%ProgramFiles%\NodeJS\node.exe`
	if a := fw.Evaluate(node); a.State != FirewallFiltered {
		t.Errorf("bloqueo del mismo programa: %+v", a)
	}
	// Sin la ruta del proceso no se puede saber: el bloqueo no cuenta.
	node.Path = ""
	if a := fw.Evaluate(node); a.State != FirewallOpen {
		t.Errorf("sin ruta: %+v", a)
	}
	// System (PID 4) no tiene ruta: se compara por nombre.
	smb := Port{Proto: "tcp", Port: 445, Addresses: []string{"0.0.0.0"}, Process: "System"}
	fw = &Firewall{Profiles: prof, Rules: []FirewallRule{
		{Name: "bloquea SMB", Protocol: 6, LocalPorts: "445", App: "System", Profiles: 7},
		{Name: "SMB", Allow: true, Protocol: 6, LocalPorts: "445", App: "System", Profiles: 7},
	}}
	if a := fw.Evaluate(smb); a.State != FirewallFiltered {
		t.Errorf("System: %+v", a)
	}
	// En un svchost compartido no se sabe qué servicio abre el puerto.
	svc := Port{Proto: "tcp", Port: 5000, Addresses: []string{"0.0.0.0"}, Process: "svchost.exe",
		Path: `C:\Windows\System32\svchost.exe`, Services: []string{"A", "B"}}
	fw = &Firewall{Profiles: prof, Rules: []FirewallRule{
		{Name: "bloquea A", Protocol: 256, App: `%SystemRoot%\system32\svchost.exe`, Service: "A", Profiles: 7},
		{Name: "permite", Allow: true, Protocol: 256, LocalPorts: "5000", Profiles: 7},
	}}
	if a := fw.Evaluate(svc); a.State != FirewallOpen {
		t.Errorf("svchost compartido: %+v", a)
	}
	svc.Services = []string{"A"}
	if a := fw.Evaluate(svc); a.State != FirewallFiltered {
		t.Errorf("servicio propio: %+v", a)
	}
}

func TestExpandWinEnv(t *testing.T) {
	env := map[string]string{"windir": `C:\Windows`, "ProgramFiles(x86)": `C:\Program Files (x86)`}
	get := func(k string) string { return env[k] }
	for in, want := range map[string]string{
		`%SystemRoot%\system32\svchost.exe`:   `C:\Windows\system32\svchost.exe`,
		`%ProgramFiles(x86)%\Steam\steam.exe`: `C:\Program Files (x86)\Steam\steam.exe`,
		`%NOEXISTE%\a.exe`:                    `%NOEXISTE%\a.exe`,
		`C:\100%\a.exe`:                       `C:\100%\a.exe`,
		`C:\Program Files\app\app.exe`:        `C:\Program Files\app\app.exe`,
	} {
		if got := expandWinEnv(in, get); got != want {
			t.Errorf("expandWinEnv(%q) = %q, quiero %q", in, got, want)
		}
	}
}

// Un bloqueo limitado a puertos de origen o a ciertos usuarios no cierra el
// puerto, y una regla así tampoco «lo permite todo».
func TestRegRuleRemotePortsAndUserAuth(t *testing.T) {
	r, ok := parseRegRule(`v2.33|Action=Block|Active=TRUE|Dir=In|Protocol=17|RPort=53|RPort2_10=Ply2Disc|Name=x|`)
	if !ok || r.RemotePorts != "53,Ply2Disc" || r.unrestricted() {
		t.Errorf("RPort: %+v", r)
	}
	r, ok = parseRegRule(`v2.33|Action=Block|Active=TRUE|Dir=In|LUAuth=O:LSD:(A;;CC;;;S-1-5-21-1)|Name=y|`)
	if !ok || !r.UserAuth || r.unrestricted() {
		t.Errorf("LUAuth: %+v", r)
	}
	prof := []FirewallProfile{{Name: "Público", Bit: 4, Enabled: true, BlockInbound: true, Active: true}}
	fw := &Firewall{Profiles: prof, Rules: []FirewallRule{
		{Name: "bloquea origen 53", Protocol: 17, RemotePorts: "53", Profiles: 7},
		{Name: "todo", Allow: true, Protocol: 256, Profiles: 7, RemotePorts: "*"},
	}}
	if a := fw.Evaluate(Port{Proto: "udp", Port: 5353, Addresses: []string{"0.0.0.0"}}); a.State != FirewallOpen {
		t.Errorf("bloqueo por puerto de origen: %+v", a)
	}
	fw.Rules[1].RemotePorts = "80"
	if len(fw.AllowAll()) != 0 {
		t.Error("una regla limitada a un puerto de origen no lo permite todo")
	}
	fw2 := parsePSFirewall(map[string]any{
		"profiles": []any{map[string]any{"Bit": 4.0, "Enabled": true, "BlockInbound": true, "Active": true}},
		"rules":    []any{map[string]any{"N": "x", "A": 1.0, "P": 6.0, "RP": "1024-65535", "Pr": 7.0}},
	})
	if fw2.Rules[0].RemotePorts != "1024-65535" {
		t.Errorf("COM RemotePorts: %+v", fw2.Rules[0])
	}
}

// Los servicios conocidos en puertos del rango dinámico no son sockets de
// cliente, y los programas con UDP dinámico en todas las interfaces se
// mencionan en una nota.
func TestEphemeralUDP(t *testing.T) {
	for _, c := range []struct {
		port, lo, hi int
		want         bool
	}{
		{52706, 49152, 65535, true},
		{51820, 49152, 65535, false}, // WireGuard
		{51820, 32768, 60999, false},
		{47998, 32768, 60999, false}, // Sunshine
		{41641, 32768, 60999, false}, // Tailscale
		{40000, 32768, 60999, true},
		{5353, 32768, 60999, false},
	} {
		if got := ephemeralUDP(c.port, c.lo, c.hi); got != c.want {
			t.Errorf("ephemeralUDP(%d, %d-%d) = %v", c.port, c.lo, c.hi, got)
		}
	}
	inv := Inventory{Listeners: []Listener{
		{Proto: "udp", Address: "0.0.0.0", Port: 50000, Scope: ScopeNetwork, PID: 7, Process: "backdoor.exe", Ephemeral: true},
		{Proto: "udp", Address: "0.0.0.0", Port: 50001, Scope: ScopeNetwork, PID: 8, Process: "svchost.exe", Services: []string{"Dnscache"}, Ephemeral: true},
		{Proto: "udp", Address: "192.168.1.5", Port: 50002, Scope: ScopeNetwork, PID: 9, Process: "chrome.exe", Ephemeral: true},
	}}
	rep := Analyze(inv, platform.Info{}, "test", time.Now())
	var note string
	for _, n := range rep.Notes {
		if strings.Contains(n, "puertos dinámicos") {
			note = n
		}
	}
	if !strings.Contains(note, "backdoor.exe") || strings.Contains(note, "svchost") || strings.Contains(note, "chrome") {
		t.Errorf("nota de UDP dinámico: %q", note)
	}
	if rep.Exposed != 0 {
		t.Errorf("los sockets dinámicos no cuentan como expuestos: %d", rep.Exposed)
	}
}

func TestParseExportsWorld(t *testing.T) {
	shares := parseExports("/srv/a\n" +
		"/srv/b 0.0.0.0/0(rw)\n" +
		"/srv/c ::/0(ro)\n" +
		"/srv/d 10.0.0.0/8(rw,no_root_squash) \\\n" +
		"    192.168.1.0/24(ro)   # comentario\n" +
		"/srv/e host1(rw)\n")
	if len(shares) != 5 {
		t.Fatalf("quiero 5 exportaciones: %+v", shares)
	}
	world := map[string]bool{}
	for _, s := range shares {
		world[s.Path] = strings.Contains(strings.Join(s.Options, ","), "*")
	}
	for path, want := range map[string]bool{"/srv/a": true, "/srv/b": true, "/srv/c": true, "/srv/d": false, "/srv/e": false} {
		if world[path] != want {
			t.Errorf("%s: para todos = %v, quiero %v", path, world[path], want)
		}
	}
	d := shares[3]
	if len(d.Access) != 2 || d.Access[1].Account != "192.168.1.0/24" || d.Options[0] != "no_root_squash" {
		t.Errorf("continuación con \\: %+v", d)
	}
	if a := shares[0].Access; len(a) != 1 || a[0].Account != "*" || a[0].Right != "Read" {
		t.Errorf("sin clientes: %+v", a)
	}
}

func TestNetstatAndTasklistRobustness(t *testing.T) {
	ls := parseNetstat("  TCP    0.0.0.0:135   0.0.0.0:0   IN ASCOLTO   1012\n  UDP    0.0.0.0:5355   *:*   1500\n")
	if len(ls) != 2 || ls[0].PID != 1012 || ls[1].PID != 1500 {
		t.Errorf("estado en varias palabras: %+v", ls)
	}
	procs := parseTasklist(`"a.exe","10","N/D"
"b"roto.exe","11","N/D"
"c.exe","12","Svc1"
`)
	if procs[10].image != "a.exe" || procs[12].image != "c.exe" || len(procs[12].services) != 1 {
		t.Errorf("una línea mal entrecomillada no debe perder las demás: %+v", procs)
	}
}

func TestSignatureEdgeCases(t *testing.T) {
	sigs := parsePSSignatures(map[string]any{"files": map[string]any{
		`C:\x\a.exe`: map[string]any{"status": "UnknownError", "signer": "CN=Caducado"},
		`C:\x\b.exe`: map[string]any{"status": "NotSupportedFileFormat", "signer": ""},
	}})
	if s := sigs[`c:\x\a.exe`]; s.status != SigUntrusted || s.signer != "Caducado" {
		t.Errorf("UnknownError: %+v", s)
	}
	if _, ok := sigs[`c:\x\b.exe`]; ok {
		t.Error("formato no admitido: sin dato")
	}
	got := parseDpkgSearch("local diversion from: /usr/bin/foo\nlocal diversion to: /usr/bin/foo.distrib\nfoo-pkg: /usr/bin/bar\n")
	if len(got) != 1 || got["/usr/bin/bar"] != "foo-pkg" {
		t.Errorf("desvíos locales: %v", got)
	}
}
